-- AMV: pauta de audición docente de ocho dimensiones.
-- Aplicar en el proyecto Supabase antes de usar Guardar evaluación docente.
create table if not exists public.vocal_teacher_evaluations (
  id bigint generated by default as identity primary key,
  recording_id bigint not null unique references public.vocal_recordings(id) on delete cascade,
  student_id bigint not null,
  teacher_id uuid not null references auth.users(id) on delete cascade,
  scores jsonb not null default '{}'::jsonb,
  observations text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vocal_teacher_evaluations_scores_object check (jsonb_typeof(scores) = 'object')
);

alter table public.vocal_teacher_evaluations enable row level security;
revoke all on public.vocal_teacher_evaluations from anon;
grant select, insert, update, delete on public.vocal_teacher_evaluations to authenticated;
grant usage, select on sequence public.vocal_teacher_evaluations_id_seq to authenticated;

-- Un profesor solo accede a las evaluaciones creadas por su propia cuenta.
create policy "teachers read own vocal evaluations"
  on public.vocal_teacher_evaluations for select to authenticated
  using (teacher_id = auth.uid() and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
create policy "teachers insert own vocal evaluations"
  on public.vocal_teacher_evaluations for insert to authenticated
  with check (teacher_id = auth.uid() and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
create policy "teachers update own vocal evaluations"
  on public.vocal_teacher_evaluations for update to authenticated
  using (teacher_id = auth.uid() and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher')) with check (teacher_id = auth.uid() and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
create policy "teachers delete own vocal evaluations"
  on public.vocal_teacher_evaluations for delete to authenticated
  using (teacher_id = auth.uid() and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
