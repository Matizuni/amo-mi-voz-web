-- AMV Vocal Engine: persistencia de evaluación docente y síntesis pedagógica.
-- Revisar contra el esquema real antes de aplicar.
-- Supone vocal_recordings.id bigint, students.id bigint y auth.users.id uuid.

create table if not exists public.vocal_teacher_evaluations (
  id bigint generated by default as identity primary key,
  recording_id bigint not null unique
    references public.vocal_recordings(id) on delete cascade,
  student_id bigint not null
    references public.students(id) on delete cascade,
  teacher_id uuid not null
    references auth.users(id) on delete cascade,
  scores jsonb not null default '{}'::jsonb,
  observations text not null default '',
  strengths text not null default '',
  priorities text not null default '',
  exercise_plan text not null default '',
  integrated_result jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vocal_teacher_evaluations_scores_object
    check (jsonb_typeof(scores) = 'object'),
  constraint vocal_teacher_evaluations_integrated_object
    check (jsonb_typeof(integrated_result) = 'object')
);

-- Permite evolucionar de forma segura si la tabla ya existía con una versión inicial.
alter table public.vocal_teacher_evaluations
  add column if not exists strengths text not null default '',
  add column if not exists priorities text not null default '',
  add column if not exists exercise_plan text not null default '',
  add column if not exists integrated_result jsonb not null default '{}'::jsonb;

alter table public.vocal_teacher_evaluations enable row level security;
revoke all on public.vocal_teacher_evaluations from anon;
grant select, insert, update on public.vocal_teacher_evaluations to authenticated;
grant usage, select on sequence public.vocal_teacher_evaluations_id_seq to authenticated;

drop policy if exists "teachers read own vocal evaluations" on public.vocal_teacher_evaluations;
drop policy if exists "teachers insert own vocal evaluations" on public.vocal_teacher_evaluations;
drop policy if exists "teachers update own vocal evaluations" on public.vocal_teacher_evaluations;

create policy "teachers read own vocal evaluations"
on public.vocal_teacher_evaluations for select to authenticated
using (
  teacher_id = auth.uid()
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher')
);

create policy "teachers insert own vocal evaluations"
on public.vocal_teacher_evaluations for insert to authenticated
with check (
  teacher_id = auth.uid()
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher')
);

create policy "teachers update own vocal evaluations"
on public.vocal_teacher_evaluations for update to authenticated
using (
  teacher_id = auth.uid()
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher')
)
with check (
  teacher_id = auth.uid()
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher')
);

create or replace function public.set_vocal_teacher_evaluation_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_vocal_teacher_evaluation_updated_at on public.vocal_teacher_evaluations;
create trigger trg_vocal_teacher_evaluation_updated_at
before update on public.vocal_teacher_evaluations
for each row execute function public.set_vocal_teacher_evaluation_updated_at();
